hit = {old: 0 for old, _ in REPL}

def apply(o):
    if isinstance(o, str):
        s = o
        for old, rep in REPL:
            if old in s:
                hit[old] += s.count(old)
                s = s.replace(old, rep)
        return s
    if isinstance(o, dict):
        return {k: apply(v) for k, v in o.items()}
    if isinstance(o, list):
        return [apply(v) for v in o]
    return o

