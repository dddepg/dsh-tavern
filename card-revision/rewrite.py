def leaves(o, path=''):
    if isinstance(o, str):       yield path, o
    elif isinstance(o, dict):
        for k, v in o.items():   yield from leaves(v, f'{path}.{k}')
    elif isinstance(o, list):
        for i, v in enumerate(o): yield from leaves(v, f'{path}[{i}]')

